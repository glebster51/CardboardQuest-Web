/** Knowledge changes what the boy says; optional detours pay off in the main plot. */
export function getStoryDialogue(state, id, kind = 'scene', optionId = null) {
  const script = STORY_DIALOGUE[id];
  if (!script) return [];
  if (id === 'bell-vault' && hasGrandpaDied(state)) return C(
    N('У треснувшего колокола лежит дед. Мальчик знает, что не услышит ответа. И всё же останавливается.'),
    H('Я тут. Просто чтобы ты знал.'), N('Вода не подражает ему. Даже она теперь молчит.'));
  const source = optionId ? script.choices?.[optionId] : script[kind];
  const result = (source ?? []).map(line => ({ ...line }));
  const flags = state.flags ?? {};
  if (kind === 'scene' && !optionId && id === 'cartographer' && flags.foundDiary) result.splice(0, 0,
    ...C(H('Я читал дневник. Можешь не готовить красивую версию.'), M('Тогда садись. Некрасивая длиннее.')));
  if (kind === 'scene' && !optionId && id === 'bell-vault') {
    if (flags.foundToy) result.push(...C(H('Я нашёл того деревянного мальчика. Ты его для меня вырезал?'),
      G('Четырежды переделывал уши. Всё получались мои.'), H('У меня твои. Не надо было переделывать.')));
    if (flags.helpedCarrier) result.push(...C(H('Я вытащил Бирку из-под моста.'),
      G('Хорошо.'), H('Не потому, что ты учил. Он руку протянул.'), G('Так даже лучше.')));
    if (flags.foundWhistleHalf) result.push(...C(H('У меня только половина свистка.'),
      G('Вторая в кармане. Сложишь — будет свистеть чуть криво.'), H('Как мы с тобой.'), G('Ага. Как мы.')));
  }
  if (kind === 'intro' && id === 'grandpa' && flags.triedToReplaceGrandpa)
    result.splice(1, 1, ...C(H('Я бы остался. Ты знаешь, я бы остался.'), N('Мальчик злится на молчание. Оно даже не пытается оправдаться.')));
  return result;
}
